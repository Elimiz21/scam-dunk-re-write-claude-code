/**
 * Inbound Email Webhook
 *
 * Receives emails forwarded by Resend (or other email services) to
 * support@scamdunk.com and automatically creates support tickets
 * routed through the email routing system.
 *
 * Setup:
 * 1. Add your domain to Resend: https://resend.com/domains
 * 2. Configure an MX record to route support@scamdunk.com to Resend inbound
 * 3. Set INBOUND_EMAIL_WEBHOOK_SECRET in your environment
 * 4. Add the webhook URL in Resend: https://yourdomain.com/api/inbound-email
 */

import { NextRequest, NextResponse } from "next/server";
import crypto from "crypto";
import { prisma } from "@/lib/db";
import {
  sendSupportTicketNotification,
  sendSupportTicketConfirmation,
} from "@/lib/email";
import { rateLimit, rateLimitExceededResponse } from "@/lib/rate-limit";

export const dynamic = "force-dynamic";

const WEBHOOK_SECRET = process.env.INBOUND_EMAIL_WEBHOOK_SECRET || "";

/** Normalize a webhook `headers` value (object map or [{name,value}] array). */
function normalizeHeaders(headers: unknown): Record<string, string> {
  const out: Record<string, string> = {};
  if (!headers) return out;
  if (Array.isArray(headers)) {
    for (const item of headers) {
      if (item && typeof item.name === "string") {
        out[item.name.toLowerCase()] = String(item.value ?? "");
      }
    }
  } else if (typeof headers === "object") {
    for (const [k, v] of Object.entries(headers as Record<string, unknown>)) {
      out[k.toLowerCase()] = String(v ?? "");
    }
  }
  return out;
}

/**
 * Detect machine-generated mail (auto-replies, out-of-office, bounces) so we
 * don't create a ticket / send a confirmation for it and start a mail loop.
 * Uses RFC 3834 headers when the webhook forwards them, with a subject-line
 * fallback for webhooks that don't.
 */
function isAutoGeneratedEmail(headers: unknown, subject: string): boolean {
  const h = normalizeHeaders(headers);
  const autoSubmitted = (h["auto-submitted"] || "").toLowerCase();
  if (autoSubmitted && autoSubmitted !== "no") return true;
  if (h["x-auto-response-suppress"]) return true;
  if (h["x-autoreply"] || h["x-autorespond"]) return true;
  const precedence = (h["precedence"] || "").toLowerCase();
  if (["bulk", "auto_reply", "junk", "list"].includes(precedence)) return true;
  return /^\s*(auto(matic)?[-\s]?reply|out[-\s]?of[-\s]?office|automatic reply|undeliverable|delivery status notification|mail delivery (failed|subsystem)|returned mail|read receipt)\b/i.test(
    subject,
  );
}

// Category detection keywords
const CATEGORY_KEYWORDS: Record<string, string[]> = {
  BUG_REPORT: [
    "bug",
    "broken",
    "error",
    "crash",
    "not working",
    "issue",
    "glitch",
    "fails",
  ],
  BILLING: [
    "billing",
    "payment",
    "charge",
    "invoice",
    "subscription",
    "refund",
    "cancel",
  ],
  FEATURE_REQUEST: [
    "feature",
    "suggestion",
    "would be nice",
    "wish",
    "request",
    "add",
    "improve",
  ],
  FEEDBACK: [
    "feedback",
    "love",
    "great",
    "amazing",
    "thank",
    "appreciate",
    "thoughts",
  ],
};

function detectCategory(subject: string, body: string): string {
  const text = `${subject} ${body}`.toLowerCase();
  for (const [category, keywords] of Object.entries(CATEGORY_KEYWORDS)) {
    if (keywords.some((kw) => text.includes(kw))) {
      return category;
    }
  }
  return "SUPPORT";
}

function extractName(fromHeader: string): string {
  // Try to extract name from "Name <email>" format
  const match = fromHeader.match(/^([^<]+)\s*</);
  if (match) return match[1].trim().replace(/"/g, "");
  // Fall back to email username
  const emailMatch = fromHeader.match(/([^@]+)@/);
  if (emailMatch) return emailMatch[1].replace(/[._-]/g, " ");
  return "Email User";
}

function extractEmail(fromHeader: string): string {
  const match = fromHeader.match(/<([^>]+)>/);
  if (match) return match[1].trim();
  // Maybe it's just a plain email
  if (fromHeader.includes("@")) return fromHeader.trim();
  return "";
}

function stripHtml(html: string): string {
  return html
    .replace(/<style[^>]*>[\s\S]*?<\/style>/gi, "")
    .replace(/<script[^>]*>[\s\S]*?<\/script>/gi, "")
    .replace(/<[^>]+>/g, " ")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/\s+/g, " ")
    .trim();
}

export async function POST(request: NextRequest) {
  try {
    // Rate limit: auth for inbound email webhook (10 requests per minute)
    const { success: rateLimitSuccess, headers: rateLimitHeaders } =
      await rateLimit(request, "auth");
    if (!rateLimitSuccess) {
      return rateLimitExceededResponse(rateLimitHeaders);
    }

    // Verify webhook secret
    if (!WEBHOOK_SECRET) {
      console.error(
        "[INBOUND EMAIL] INBOUND_EMAIL_WEBHOOK_SECRET not configured",
      );
      return NextResponse.json(
        { error: "Webhook not configured" },
        { status: 503 },
      );
    }

    const authHeader = request.headers.get("authorization");
    const webhookHeader = request.headers.get("x-webhook-secret");
    const token = authHeader?.replace("Bearer ", "") || webhookHeader || "";

    const tokenBuf = Buffer.from(token);
    const secretBuf = Buffer.from(WEBHOOK_SECRET);
    if (
      tokenBuf.length !== secretBuf.length ||
      !crypto.timingSafeEqual(tokenBuf, secretBuf)
    ) {
      console.error("[INBOUND EMAIL] Invalid webhook secret");
      return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
    }

    const body = await request.json();

    // Support multiple webhook formats:
    // 1. Resend inbound: { from, to, subject, text, html }
    // 2. Generic/forwarded: { from, subject, body/text/html }
    const from = body.from || body.sender || "";
    const subject = body.subject || "(No subject)";
    const textBody = body.text || body.body || "";
    const htmlBody = body.html || "";
    const message = textBody || stripHtml(htmlBody);

    if (!from) {
      return NextResponse.json(
        { error: "Missing required field: from" },
        { status: 400 },
      );
    }

    const senderEmail = extractEmail(from);
    const senderName = extractName(from);

    if (!senderEmail) {
      return NextResponse.json(
        { error: "Could not extract email address from sender" },
        { status: 400 },
      );
    }

    if (!message || message.length < 5) {
      return NextResponse.json(
        { error: "Email body is empty or too short" },
        { status: 400 },
      );
    }

    // Break auto-responder loops: our confirmation email triggers the sender's
    // vacation/auto-reply, which we'd otherwise turn into a new ticket + another
    // confirmation, ad infinitum. Ignore machine-generated mail entirely (R9).
    if (isAutoGeneratedEmail(body.headers, subject)) {
      console.log(
        `[INBOUND EMAIL] Ignoring auto-generated email from ${senderEmail} (subject: ${subject.slice(0, 80)})`,
      );
      return NextResponse.json({ ok: true, ignored: "auto-generated" });
    }

    // Auto-detect category from content
    const category = detectCategory(subject, message);

    // Auto-assign priority
    let priority = "NORMAL";
    if (category === "BUG_REPORT" || category === "BILLING") {
      priority = "HIGH";
    }

    // Create the support ticket
    const ticket = await prisma.supportTicket.create({
      data: {
        name: senderName,
        email: senderEmail,
        subject: subject.substring(0, 200),
        message: message.substring(0, 5000),
        category,
        priority,
        status: "NEW",
        ipAddress: "inbound-email",
        userAgent: "Inbound Email Webhook",
        lastActivityAt: new Date(),
      },
    });

    // Route notifications through the email routing system
    try {
      await sendSupportTicketNotification(
        ticket.id,
        senderName,
        senderEmail,
        subject,
        message.substring(0, 2000),
        category,
      );

      await sendSupportTicketConfirmation(
        ticket.id,
        senderName,
        senderEmail,
        subject,
        category,
      );
    } catch (emailError) {
      console.error(
        "[INBOUND EMAIL] Failed to send notification emails:",
        emailError,
      );
    }

    console.log(
      `[INBOUND EMAIL] Created ticket ${ticket.id} from ${senderEmail} (category: ${category})`,
    );

    return NextResponse.json(
      {
        success: true,
        ticketId: ticket.id,
        category,
        priority,
      },
      { status: 201 },
    );
  } catch (error) {
    console.error("[INBOUND EMAIL] Webhook error:", error);
    return NextResponse.json(
      { error: "Failed to process inbound email" },
      { status: 500 },
    );
  }
}
